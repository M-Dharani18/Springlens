"""
entity_coverage_gemini.py
──────────────────────────
Re-runs entity coverage evaluation using Gemini-generated answers.

Why redo this?
- Original run_experiments.py used llama3.2:1b (1B parameter model) for generation
- Small models produce shorter answers → lower entity mentions → underestimates C3/C4
- This script uses the answers generated by gemini-3.5-flash-lite (fetch_direct.py)
- Gemini can properly utilize AST metadata, so C3/C4 should show better coverage

Input:  ragas_raw_subset.json   (Gemini-generated answers per condition)
        benchmark_petclinic.json (expected_entities per question)
Output: entity_coverage_gemini.csv
        entity_coverage_summary.csv
"""
import json
import os
import pandas as pd
from collections import defaultdict

os.chdir(os.path.dirname(os.path.abspath(__file__)))
print(f"Working directory: {os.getcwd()}")

# ── Load data ────────────────────────────────────────────────────────────────
if os.path.exists("ragas_faithfulness_results.csv"):
    ragas_df = pd.read_csv("ragas_faithfulness_results.csv")
    ragas_rows = ragas_df.to_dict("records")
else:
    with open("ragas_raw_subset.json") as f:
        ragas_rows = json.load(f)

# Load BOTH benchmarks for entity lookup
benchmark = []
for bfile in ["benchmark_petclinic.json", "benchmark_realworld.json"]:
    with open(bfile) as f:
        benchmark.extend(json.load(f))

# Build lookup: question_id → expected_entities
entity_map = {item["id"]: item.get("expected_entities", []) for item in benchmark}

print(f"Loaded {len(ragas_rows)} Gemini-generated answers")
print(f"Benchmark has {len(benchmark)} questions with expected entities\n")

# ── Compute entity coverage ───────────────────────────────────────────────────
def compute_coverage(answer_text, expected_entities):
    """Case-insensitive substring match for each expected entity."""
    if not answer_text or not expected_entities or pd.isna(answer_text):
        return 0.0, [], []
    answer_lower = str(answer_text).lower()
    found   = [e for e in expected_entities if e.lower() in answer_lower]
    missing = [e for e in expected_entities if e.lower() not in answer_lower]
    return len(found) / len(expected_entities), found, missing


results = []
condition_scores = defaultdict(list)

print(f"{'ID':<18} {'Cond':<5} {'Strategy':<15} {'Retrieval':<8} {'Coverage':>8}  {'Found'}")
print("─" * 90)

for row in ragas_rows:
    q_id      = row["id"]
    condition = row["condition"]
    strategy  = row["strategy"]
    retrieval = row["retrieval"]
    answer    = row.get("response", row.get("answer", ""))

    expected = entity_map.get(q_id, [])
    if not expected:
        print(f"  WARNING: No expected_entities for {q_id} — skipping")
        continue

    score, found, missing = compute_coverage(answer, expected)
    condition_scores[condition].append(score)

    results.append({
        "id":              q_id,
        "condition":       condition,
        "strategy":        strategy,
        "retrieval":       retrieval,
        "entity_coverage": round(score, 4),
        "entities_found":  len(found),
        "entities_total":  len(expected),
        "found":           ", ".join(found),
        "missing":         ", ".join(missing),
        "answer_len":      len(answer),
    })

    bar = "█" * int(score * 10) + "░" * (10 - int(score * 10))
    print(f"{q_id:<18} {condition:<5} {strategy:<15} {retrieval:<8} "
          f"{score:>7.1%}  [{bar}]  {found}")

# ── Summary by condition ──────────────────────────────────────────────────────
print("\n" + "═" * 60)
print("ENTITY COVERAGE — Mean by Condition (Gemini-generated answers)")
print("═" * 60)

label = {
    "C1": "Generic Token  + Dense  (baseline)",
    "C2": "Generic Token  + Hybrid",
    "C3": "AST Framework  + Dense",
    "C4": "AST Framework  + Hybrid",
}

summary_rows = []
for cond in ["C1", "C2", "C3", "C4"]:
    scores = condition_scores[cond]
    if scores:
        mean  = sum(scores) / len(scores)
        mn, mx = min(scores), max(scores)
        bar = "█" * int(mean * 10) + "░" * (10 - int(mean * 10))
        print(f"  {cond}: {mean:.3f}  [{bar}]  n={len(scores)}  "
              f"range=[{mn:.3f}, {mx:.3f}]  — {label[cond]}")
        summary_rows.append({
            "condition": cond,
            "description": label[cond],
            "mean_entity_coverage": round(mean, 4),
            "n": len(scores),
            "min": round(mn, 4),
            "max": round(mx, 4),
        })

# ── Save to CSV ───────────────────────────────────────────────────────────────
import csv

with open("entity_coverage_gemini.csv", "w", newline="") as f:
    writer = csv.DictWriter(f, fieldnames=results[0].keys())
    writer.writeheader()
    writer.writerows(results)

with open("entity_coverage_summary.csv", "w", newline="") as f:
    writer = csv.DictWriter(f, fieldnames=summary_rows[0].keys())
    writer.writeheader()
    writer.writerows(summary_rows)

print("\nSaved: entity_coverage_gemini.csv  (per-row)")
print("Saved: entity_coverage_summary.csv (per-condition means)")
print("\nNext: compare these results vs the old llama3.2:1b run")
